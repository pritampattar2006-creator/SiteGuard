"""PDF reports: a notice for one violation, and a summary of many with a time log, worker names and evidence."""
from __future__ import annotations

import io
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

NAVY = colors.HexColor("#0b3d62")
GREY = colors.HexColor("#5f6b76")
LINE = colors.HexColor("#c9d3da")
STATUS_COLOUR = {
    "Open": "#d93025", "Disputed": "#e08a00", "Acknowledged": "#0b5cad", "Resolved": "#2e9e55", "Dismissed": "#5f6b76",
}

_styles = getSampleStyleSheet()
BODY = ParagraphStyle("body", parent=_styles["BodyText"], fontSize=9.5, leading=12.5)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8.2, leading=10.5, textColor=GREY)
H1 = ParagraphStyle("h1", parent=_styles["Title"], fontSize=19, leading=23, textColor=NAVY, alignment=0, spaceAfter=2)
H2 = ParagraphStyle("h2", parent=_styles["Heading2"], fontSize=12, textColor=NAVY, spaceBefore=10, spaceAfter=4)


def _image(path: str, max_w: float, max_h: float):
    """An image scaled to fit the box, or a grey note if the file is missing."""
    if path and Path(path).exists():
        img = Image(path)
        scale = min(max_w / img.imageWidth, max_h / img.imageHeight, 1.0)
        img.drawWidth, img.drawHeight = img.imageWidth * scale, img.imageHeight * scale
        return img
    return Paragraph("<i>image not available</i>", SMALL)


def _chip(status: str) -> str:
    return f'<font color="{STATUS_COLOUR.get(status, "#5f6b76")}"><b>{status}</b></font>'


def _when(value: str) -> str:
    return value.replace("T", " ") if value else ""


def _doc(buffer, title: str) -> SimpleDocTemplate:
    return SimpleDocTemplate(buffer, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=14 * mm,
                             bottomMargin=14 * mm, title=title, author="PPE Compliance Detection")


def _footer(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(GREY)
    canvas.drawString(15 * mm, 8 * mm, "Generated by PPE Compliance Detection. Detections are automated and reviewed by a supervisor.")
    canvas.drawRightString(195 * mm, 8 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _grid(rows: list[list], widths: list[float], header: bool = False) -> Table:
    table = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
    table.setStyle(TableStyle(style))
    return table


def notice_pdf(violation, events) -> bytes:
    """One-page notice for a single violation: evidence, worker name, time, and the full time log."""
    buffer = io.BytesIO()
    worker = violation["worker_name"] or "Not assigned"
    emp = f" ({violation['employee_id']})" if violation["employee_id"] else ""
    story = [
        Paragraph(f"PPE Violation Notice #{violation['id']:05d}", H1),
        Paragraph(f"Status: {_chip(violation['status'])} &nbsp;&nbsp; Recorded {_when(violation['recorded_at'])}", BODY),
        Spacer(1, 6),
        _grid(
            [
                [Paragraph("<b>Worker</b>", BODY), Paragraph(f"{worker}{emp}", BODY)],
                [Paragraph("<b>Department</b>", BODY), Paragraph(violation["department"] or "-", BODY)],
                [Paragraph("<b>Seen in image as</b>", BODY), Paragraph(violation["worker_ref"], BODY)],
                [Paragraph("<b>Violation</b>", BODY), Paragraph(f"<b>{violation['missing']}</b>", BODY)],
                [Paragraph("<b>Date and time</b>", BODY), Paragraph(_when(violation["occurred_at"]), BODY)],
                [Paragraph("<b>Location / camera</b>", BODY), Paragraph(violation["location"] or "-", BODY)],
                [Paragraph("<b>Source</b>", BODY), Paragraph(
                    violation["source_name"] or violation["source"]
                    + (f" at {violation['video_time_s']:.1f} s into the clip" if violation["video_time_s"] is not None else ""), BODY)],
                [Paragraph("<b>Why it was flagged</b>", BODY), Paragraph(violation["reason"] or "-", BODY)],
            ],
            [45 * mm, 135 * mm],
        ),
        Paragraph("Evidence", H2),
        Table(
            [[_image(violation["evidence_path"], 118 * mm, 95 * mm), _image(violation["crop_path"], 58 * mm, 95 * mm)]],
            colWidths=[121 * mm, 61 * mm],
        ),
        Paragraph("Time log", H2),
    ]
    rows = [[Paragraph(h, BODY) for h in ("Time", "By", "Action", "Note")]]
    rows += [[Paragraph(_when(e["at"]), SMALL), Paragraph(e["actor"], SMALL), Paragraph(e["action"], SMALL), Paragraph(e["note"], SMALL)] for e in events]
    story.append(_grid(rows, [38 * mm, 32 * mm, 30 * mm, 80 * mm], header=True))
    _doc(buffer, f"Violation notice {violation['id']}").build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def summary_pdf(rows, stats: dict, title: str = "PPE Violation Summary", period: str = "") -> bytes:
    """Summary of many violations: headline counts, then a time-ordered log with worker names and evidence thumbnails."""
    buffer = io.BytesIO()
    items = ", ".join(f"{name}: {n}" for name, n in stats["by_item"].items()) or "none"
    story = [
        Paragraph(title, H1),
        Paragraph(period or "All recorded violations", SMALL),
        Spacer(1, 6),
        _grid(
            [[Paragraph(f"<b>{stats['total']}</b><br/>violations", BODY), Paragraph(f"<b>{stats['open']}</b><br/>open or disputed", BODY),
              Paragraph(f"<b>{stats['by_status']['Resolved']}</b><br/>resolved", BODY),
              Paragraph(f"<b>{len(stats['by_worker'])}</b><br/>workers involved", BODY)]],
            [45 * mm] * 4,
        ),
        Spacer(1, 4),
        Paragraph(f"<b>By missing item:</b> {items}", BODY),
        Paragraph("Time log", H2),
    ]
    header = [Paragraph(h, BODY) for h in ("#", "Time", "Worker", "Violation", "Evidence", "Status")]
    table_rows = [header]
    for r in sorted(rows, key=lambda r: r["occurred_at"]):
        who = r["worker_name"] or f"Unassigned ({r['worker_ref']})"
        emp = f"<br/>{r['employee_id']}" if r["employee_id"] else ""
        table_rows.append([
            Paragraph(f"{r['id']:05d}", SMALL),
            Paragraph(_when(r["occurred_at"]) + (f"<br/>clip {r['video_time_s']:.1f} s" if r["video_time_s"] is not None else ""), SMALL),
            Paragraph(f"<b>{who}</b>{emp}", SMALL),
            Paragraph(f"<b>{r['missing']}</b><br/>{r['location'] or ''}", SMALL),
            _image(r["crop_path"] or r["evidence_path"], 30 * mm, 30 * mm),
            Paragraph(_chip(r["status"]), SMALL),
        ])
    if len(table_rows) == 1:
        story.append(Paragraph("No violations in this period.", BODY))
    else:
        story.append(_grid(table_rows, [12 * mm, 30 * mm, 38 * mm, 42 * mm, 36 * mm, 22 * mm], header=True))
    _doc(buffer, title).build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()
